    private uint? loadedInstanceContent;

    // ── 防火牆自檢用的觀測狀態（B-001）──────────────────────────────────
    //
    // 兩個 hook 從 plugin 載入起就常駐啟用，但分兩種模式：
    //   Passive  — 只計數，一律呼叫 Original（＝完全不改變遊戲行為）
    //   Blocking — 真正的防火牆（送出只放行心跳；接收只放行 allowlist）
    //
    // 為什麼要有 Passive：防火牆最危險的失效是「hook 沒掛上」或「掃到錯的函式」，
    // 這兩種情況下畫面全正常、build 全綠、沒有任何警告，但封包會照送給伺服器。
    // 常駐 Passive 讓我們在**進入模擬區之前**就能觀察到「detour 確實會被呼叫」
    // 以及「心跳 opcode 判定正確」——看到心跳通過一次，這兩件事同時被證明。
    // 這樣自檢不必等待、也不必為了檢查而阻斷任何封包。
    // volatile：由 framework thread 寫入、由封包 detour 讀取（不保證同一條 thread），
    // 沒有 volatile 的話 JIT 可以把讀取提到迴圈外或快取住舊值——
    // 那會讓「已切到 Blocking」與「detour 仍在放行」出現時間差，正是不能接受的。
    private volatile bool blocking;

    private long sendSeenTotal;       // detour 被呼叫的總次數（證明 hook 活著）
    private long sendSeenHeartbeat;   // 其中判定為心跳的次數（證明 opcode 對）
    private long recvSeenTotal;

    // 絆線：Blocking 期間，心跳以外的封包絕不該走到 Original。
    // 這在程式邏輯上不可能發生；一旦非 0 代表有人改壞了 detour，屬立即中止的訊號。
    private long blockedLeakCount;

    internal long SendSeenTotal => Interlocked.Read(ref sendSeenTotal);
    internal long SendSeenHeartbeat => Interlocked.Read(ref sendSeenHeartbeat);
    internal long RecvSeenTotal => Interlocked.Read(ref recvSeenTotal);
    internal long BlockedLeakCount => Interlocked.Read(ref blockedLeakCount);
    internal ushort HeartbeatOpcode => heartbeatOpcode;
    internal bool SendHookLive => sendPacketHook is { IsDisposed: false, IsEnabled: true };
    internal bool RecvHookLive => receivePacketHook is { IsDisposed: false, IsEnabled: true };
    internal nint SendHookAddress => sendPacketHook?.Address ?? 0;
    internal nint RecvHookAddress => receivePacketHook?.Address ?? 0;

    // Set true right before we open the Social window for a party resync; the Social
    // PostSetup listener closes it again and clears this. Distinguishes our open from
    // a manual one so manual opens aren't auto-closed.
    private bool autoCloseSocial;

    private readonly ZoneRestoration restoration;
    public bool IsActive => restoration.IsActive;
    public bool IsRestoring => restoration.IsRestoring;
    internal bool HasRestoreFailed => restoration.HasFailed;
    internal OpcodeAllowlist IncomingOpcodes { get; } = new();
