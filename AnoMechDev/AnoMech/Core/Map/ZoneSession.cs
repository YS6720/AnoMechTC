            || c[ConditionFlag.Occupied];
    }

    // Load the target territory, teleport player to playerSpawn, enable firewall.
    // Firewall is enabled before the zone load (matching Hyperborea's sequence).
    public void Enter(uint territoryId, Vector3 playerSpawn, byte levelSync, ushort itemLevelSync, uint layerFilterKey = 0)
    {
        ContentFinderCondition? cfc = null;
        try
        {
            restoration.Enter(
                () =>
                {
                    var localPlayer = Plugin.ObjectTable.LocalPlayer;
                    var gm = GameMain.Instance();
                    if (localPlayer == null || localPlayer.Address == 0 || gm == null ||
                        EventFramework.Instance() == null || Conditions.Instance() == null ||
                        (itemLevelSync != 0 && UIState.Instance() == null))
                        throw new InvalidOperationException("Zone entry requires the local player and native singletons.");
                    cfc = GetContentFinderCondition(territoryId)
                        ?? throw new InvalidOperationException($"Territory {territoryId} has no content finder condition.");
                    var position = localPlayer.Position;
                    var rotation = localPlayer.Rotation;
                    var savedTerritory = gm->CurrentTerritoryTypeId;
                    if (!ZoneRestoration.MatchesPose(savedTerritory, savedTerritory,
                            position, position, rotation, rotation))
                        throw new InvalidOperationException("The original territory or player pose cannot be restored.");

                    sessionSave.TerritoryId = savedTerritory;
                    sessionSave.Position = position;
                    sessionSave.Rotation = rotation;
                    sessionSave.Exp = Plugin.PlayerState.GetClassJobExperience(Plugin.PlayerState.ClassJob.Value);
                    sessionSave.RestedExp = Plugin.PlayerState.BaseRestedExperience;
                    sessionSave.LevelSync = levelSync != 0;
                    sessionSave.Level = localPlayer.Level;
                    sessionSave.ItemLevelSync = itemLevelSync != 0;
                    sessionSave.Attributes.Clear();
                },
                () =>
                {
                    ++zoneGeneration;
                    EnableFirewall();
                    LoadZoneInternal(territoryId, false, playerSpawn,
                        layerFilterKey: layerFilterKey, contentFinderCondition: cfc);
                    CrashTrace.Log($"[ZoneSession] Entered territory {territoryId}.");
                });
        }
        catch
        {
            // 前置失敗不凍結玩家；native變更開始後的失敗仍由同一離場流程恢復。
            if (restoration.HasFailed)
            {
                var condition = Conditions.Instance();
                if (condition != null) condition->Occupied = true;
            }
            throw;
        }
    }

    // Immediately set the active weather. Must be called on the framework thread.
    // weatherId is a Weather-sheet row; transition is the fade time in seconds.
    public void SetWeather(byte weatherId, float transition = 0.5f)
    {
        var env = EnvManager.Instance();
        if (env == null) return;
        env->ActiveWeather = weatherId;
        env->TransitionTime = transition;
    }

    // Apply weather after a fresh zone load. Delayed 1 second so the engine finishes setup.
    //
    // RunOnTick rather than Task.Delay(...).ContinueWith(... Framework.Run ...): the latter keeps
    // the timer on the thread pool, so an unload during the delay window leaves the continuation
    // to fire against a torn-down framework (or never fire at all). RunOnTick owns both the delay
    // and the thread affinity and is cancelled with the framework. Same shape for the two delayed
    // tasks in Revert below — all three were the ContinueWith form before 2026-08-23.
    public void ApplyWeather(byte weatherId)
    {
        var generation = zoneGeneration;
        var guard = networkRunGuard;
        Plugin.Framework.RunOnTick(() =>
        {
            if (!disposed && generation == zoneGeneration && guard?.Invoke() != false)
                SetWeather(weatherId);
        }, TimeSpan.FromSeconds(1));
    }

    // 正常離場只在延遲驗證成功後交還控制；失敗保留資料及隔離供明示重試。
    // Dispose維持既有同步停用策略，不能冒稱卸載後仍有防火牆或安全熱reload。
    public void Revert(bool dispose)
    {
        if (!dispose)
        {
            restoration.Revert();
            return;
        }

        var needsRestore = restoration.IsActive;
        restoration.Dispose();
        ++zoneGeneration;
        if (!needsRestore) return;

        // 卸載時不能等待framework callback；這是舊停用契約，不供正常Leave使用。
        try
        {
            if (sessionSave.TerritoryId != 0)
                LoadZoneInternal(sessionSave.TerritoryId, true, sessionSave.Position, sessionSave.Rotation);
        }
        catch (Exception ex)
        {
            CrashTrace.Log($"[ZoneSession] Revert(dispose) LoadZoneInternal failed: {ex}");
        }
        try
        {
            SetLocalPlayerPosition(sessionSave.Position, sessionSave.Rotation);
        }
        catch (Exception ex)
        {
            CrashTrace.Log($"[ZoneSession] Revert(dispose) cleanup failed: {ex}");
        }
        finally
        {
            var condition = Conditions.Instance();
            if (condition != null) condition->Occupied = false;
            else CrashTrace.Log("[ZoneSession] Conditions.Instance() was null; Occupied not cleared.");
            DisableFirewall();
            sessionSave.TerritoryId = 0;
        }
        Plugin.Framework.Run(OpenSocialForPartyResync);
    }

    private void RestoreSavedZone()
    {
        ++zoneGeneration; // 使舊天候／Social callback失效，不清除復原資料。
        if (sessionSave.TerritoryId == 0)
            throw new InvalidOperationException("No original territory is available for restoration.");
        var condition = Conditions.Instance();
        if (condition == null)
            throw new InvalidOperationException("Conditions is unavailable during zone restoration.");
        condition->Occupied = true;
        LoadZoneInternal(sessionSave.TerritoryId, true, sessionSave.Position, sessionSave.Rotation);
    }

    private void CompleteRestoration()
    {
        if (restoreCompletionGuard?.Invoke() == false)
            throw new InvalidOperationException("Simulation cleanup is incomplete; zone isolation must remain enabled.");
        // 仍在framework thread，且已保留原本1秒延遲；不能在失敗的finally放行。
        SetLocalPlayerPosition(sessionSave.Position, sessionSave.Rotation);
        var localPlayer = Plugin.ObjectTable.LocalPlayer;
        var gm = GameMain.Instance();
        if (localPlayer == null || localPlayer.Address == 0 || gm == null ||
            !ZoneRestoration.MatchesPose(gm->CurrentTerritoryTypeId, sessionSave.TerritoryId,
                localPlayer.Position, sessionSave.Position, localPlayer.Rotation, sessionSave.Rotation))
            throw new InvalidOperationException("Original native territory/player pose has not been restored "
                + "(position tolerance=0.01, rotation tolerance=0.001 rad).");
        if (sessionSave.LevelSync && localPlayer.Level != sessionSave.Level)
            throw new InvalidOperationException("Original player level has not been restored.");
        if (sessionSave.ItemLevelSync && sessionSave.Attributes.Count != 0)
        {
            var uiState = UIState.Instance();
            if (uiState == null)
                throw new InvalidOperationException("UIState is unavailable while verifying restored attributes.");
            foreach (var (baseParamId, value) in sessionSave.Attributes)
                if (uiState->PlayerState.Attributes[baseParamId] != value)
                    throw new InvalidOperationException($"Original attribute {baseParamId} has not been restored.");
        }
        var condition = Conditions.Instance();
        if (condition == null)
            throw new InvalidOperationException("Conditions is unavailable at restoration completion.");
        condition->Occupied = false;
        DisableFirewall();
        sessionSave.TerritoryId = 0;
        sessionSave.Attributes.Clear();
        CrashTrace.Log("[ZoneSession] Original territory, player pose and sync restored.");

        // 原Social回覆會更新MainGroup／HUD；成功恢復後才排這個非必要操作。
        var generation = zoneGeneration;
        try
        {
            Plugin.Framework.RunOnTick(() =>
            {
                if (!disposed && generation == zoneGeneration && !IsActive)
                    OpenSocialForPartyResync();
            }, TimeSpan.FromMilliseconds(500));
        }
        catch (Exception ex)
        {
            CrashTrace.Log($"[ZoneSession] Party HUD resync scheduling failed after restoration: {ex}");
        }
    }

    // Opens the Social agent, which issues its own (callback-routed) party-member
    // request and processes the reply into the party HUD — the step a bare RequestData
    // can't trigger. Firing this from the settled inn state mirrors a manual open.
    private void OpenSocialForPartyResync()
    {
        var am = AgentModule.Instance();
        var social = am != null ? am->GetAgentByInternalId(AgentId.Social) : null;
        if (social == null) return;
        autoCloseSocial = true;
        social->Show();
        CrashTrace.Log("[ZoneSession] Opened Social for party resync.");
    }

    // Closes the Social window again as soon as it finishes opening — but only when
    // we opened it (autoCloseSocial), so a manual open is left alone.
    private void OnSocialPostSetup(AddonEvent type, AddonArgs args)
    {
        if (!autoCloseSocial) return;
        autoCloseSocial = false;

        var am = AgentModule.Instance();
        var s = am != null ? am->GetAgentByInternalId(AgentId.Social) : null;
        if (s != null) s->Hide();
        CrashTrace.Log("[ZoneSession] Auto-closed Social after party resync.");
    }

    // hook 本身常駐（見建構函式），這裡只切換 Passive ↔ Blocking。
    // 刻意不再 Enable/Disable hook：hook 的安裝與拆卸是有風險的操作，
    // 而且「已安裝」正是自檢要驗證的前提，反覆拆裝會讓自檢結果失效。
    public void EnableFirewall()
    {
        blocking = true;
        CrashTrace.Log("[ZoneSession] 防火牆模式 → Blocking");
    }

    public void DisableFirewall()
    {
        blocking = false;
        CrashTrace.Log("[ZoneSession] 防火牆模式 → Passive");
    }

    // ── Zone loading sequence (mirrors Hyperborea Utils.LoadZone) ─────────────

    private void LoadZoneInternal(uint territory, bool unloading, Vector3 playerPos, float? rotation = null,
        uint layerFilterKey = 0, ContentFinderCondition? contentFinderCondition = null)
    {
        var eventFramework = EventFramework.Instance();
        var gm = GameMain.Instance();
        CrashTrace.Log($"[ZoneSession] LoadZone territory={territory} ef={((nint)eventFramework):X} gm={((nint)gm):X}");
        if (eventFramework == null || gm == null)
        {
            throw new InvalidOperationException("Native zone-loading singletons are unavailable.");
        }

        var localPlayer = Plugin.ObjectTable.LocalPlayer;
        if (localPlayer == null || localPlayer.Address == 0)
            throw new InvalidOperationException("The local player is unavailable during zone loading.");
        var player = (Character*)localPlayer.Address;

        var classJobId = (byte)Plugin.PlayerState.ClassJob.RowId;

        CrashTrace.Log("[ZoneSession] Step 1: FinalizeInstanceContent");
        if (unloading || loadedInstanceContent != null)
        {
            var uiState = UIState.Instance();
            ZoneRestoration.RestoreInstanceState(ref loadedInstanceContent,
                contentId =>
                {
                    if (uiState != null) uiState->DirectorTodo.IsShown = false;
                    EventFrameworkPointers.TerminateDirector(eventFramework, 0x80030000 + contentId);
                },
                () => ResetSync(uiState, player, classJobId));
        }

        CrashTrace.Log("[ZoneSession] Step 2: DisableDraw all objects");
        foreach (var obj in Plugin.ObjectTable)
        {
            if (obj.Address == IntPtr.Zero) continue;
            ((FFXIVClientStructs.FFXIV.Client.Game.Object.GameObject*)obj.Address)->DisableDraw();
        }

        if (!unloading)
        {
            CrashTrace.Log("[ZoneSession] Step 3: InitDirector");

            var cfc = contentFinderCondition
                ?? throw new InvalidOperationException("Zone entry requires a prevalidated content finder condition.");

            var contentId = cfc.Content.RowId;
            CrashTrace.Log($"[ZoneSession] ContentId={contentId}");

            EventFrameworkPointers.InitDirector(eventFramework, 0x80030000 + contentId, contentId, 0);

            loadedInstanceContent = contentId;
            InstanceContentDirectorHelper.SetDutyData(cfc);

            SetSync(cfc, player, territory, classJobId);
        }
        else
        {
            CrashTrace.Log("[ZoneSession] Step 3: InitDirector (Skipped)");
        }

        CrashTrace.Log($"[ZoneSession] Step 4: LoadZone (native) layerFilterKey={layerFilterKey}");
        GameMainPointers.LoadZone(gm, territory, layerFilterKey, 0, 1);

        CrashTrace.Log("[ZoneSession] Step 5: SetupTerritoryType");
        eventFramework->SetTerritoryTypeId((ushort)territory);

        CrashTrace.Log("[ZoneSession] Step 6: SyncClientState");
        SyncClientStateTerritoryType((ushort)territory);

        CrashTrace.Log("[ZoneSession] Step 7: SetPosition");
        SetLocalPlayerPosition(playerPos, rotation);

        CrashTrace.Log("[ZoneSession] LoadZone complete");
    }

    private void SetLocalPlayerPosition(Vector3 position, float? rotation = null)
    {
        if (Plugin.ObjectTable.LocalPlayer is { Address: var addr } && addr != IntPtr.Zero)
        {
            var chara = (Character*)addr;
            chara->GameObject.SetPosition(position.X, position.Y, position.Z);

            if (rotation != null)
            {
                chara->GameObject.SetRotation(rotation.Value);
            }
        }
        else
        {
            throw new InvalidOperationException("The local player is unavailable for position restoration.");
        }
    }

    private ContentFinderCondition? GetContentFinderCondition(uint territoryId)
    {
        var sheet = Plugin.DataManager.GetExcelSheet<TerritoryType>();

        if (sheet == null)
        {
            Plugin.Log.Debug($"[ZoneSession.GetContentFinderCondition] TerritoryType sheet was null.");
            return null;
        }

        var rowRef = sheet[territoryId].ContentFinderCondition;

        if (!rowRef.IsValid)
        {
            Plugin.Log.Debug($"TerritoryType sheet, index {territoryId} does not have a valid ContentFinderCondition reference.");
            return null;
        }

        return rowRef.Value;
    }

    private static void SyncClientStateTerritoryType(ushort territory)
    {
        try
