    private Func<bool>? restoreCompletionGuard;

    internal void SetRestoreCompletionGuard(Func<bool> guard) => restoreCompletionGuard = guard;

    internal void SetNetworkRunGuard(Func<bool>? guard) => networkRunGuard = guard;

    private readonly SessionSave sessionSave = new();

    private void ReportRestorationFailure(Exception error)
    {
        const string instruction = "[AnoMech] 場地恢復失敗，已維持安全隔離。"
            + "請輸入 /anomech leave 重試；若仍失敗，請重新啟動遊戲，勿熱重新載入插件。";
        CrashTrace.Log($"{instruction} {error}");
        var generation = zoneGeneration;
        try
        {
            // Queue failures can be reported by a background Task observer.
            _ = Plugin.Framework.Run(() =>
            {
                if (!disposed && generation == zoneGeneration && restoration.HasFailed)
                    ChatOutput.Error(instruction, required: true);
            }).ContinueWith(
                task => CrashTrace.Log($"[ZoneSession] Recovery notification failed: {task.Exception}"),
                System.Threading.CancellationToken.None,
                System.Threading.Tasks.TaskContinuationOptions.OnlyOnFaulted |
                System.Threading.Tasks.TaskContinuationOptions.ExecuteSynchronously,
                System.Threading.Tasks.TaskScheduler.Default);
        }
        catch (Exception dispatchError)
        {
            CrashTrace.Log($"[ZoneSession] Recovery notification could not be queued: {dispatchError}");
        }
    }

    // ── Construction ──────────────────────────────────────────────────────────

    public ZoneSession()
    {
        restoration = new ZoneRestoration(
            RestoreSavedZone,
            CompleteRestoration,
            completion => Plugin.Framework.RunOnTick(completion, TimeSpan.FromSeconds(1)),
            ReportRestorationFailure);

        // Heartbeat (ZoneUp) opcode — auto-detected by signature (from Hyperborea Memory.cs)
        heartbeatOpcode = (ushort)Marshal.ReadInt32(
            Plugin.SigScanner.ScanText("C7 44 24 ?? ?? ?? ?? ?? 48 F7 F1") + 0x4);
        CrashTrace.Log($"[ZoneSession] Heartbeat opcode: {heartbeatOpcode}");

        // Send-packet hook (sig from Hyperborea Memory.cs)
        var sendAddr = Plugin.SigScanner.ScanText(
            "48 89 5C 24 ?? 48 89 74 24 ?? 4C 89 64 24 ?? 55 41 56 41 57 48 8B EC 48 83 EC 70");
        sendPacketHook = Plugin.GameInterop.HookFromAddress<SendPacketDelegate>(
            sendAddr, SendPacketDetour);

        // Receive-packet hook — address from PacketDispatcher.StaticVirtualTablePointer->OnReceivePacket.
        // This is the standard approach used by ECommons/Dalamud's GameNetwork service.
        // PacketDispatcher.Delegates.OnReceivePacket and StaticVirtualTablePointer are generated by
        // FFXIVClientStructs from [VirtualFunction(1)] + [VirtualTable] on PacketDispatcher.
        var receiveAddr = (nint)PacketDispatcher.StaticVirtualTablePointer->OnReceivePacket;
        CrashTrace.Log($"[ZoneSession] OnReceivePacket: {receiveAddr:X}");
        receivePacketHook = Plugin.GameInterop.HookFromAddress<OnReceivePacket>(
            receiveAddr, ReceivePacketDetour);

        Plugin.AddonLifecycle.RegisterListener(AddonEvent.PostSetup, "Social", OnSocialPostSetup);

        // 兩個 hook 從這裡起常駐啟用，但以 Passive 模式運作（只計數、一律放行）。
        // 這讓 FirewallSelfCheck 能在進入模擬區之前就證明 hook 真的活著、
        // 且心跳 opcode 判定正確——見上方 blocking 欄位的註解。
        // Passive 對遊戲沒有行為影響：每個封包只多一次 opcode 比對與計數。
        sendPacketHook.Enable();
        receivePacketHook.Enable();

        CrashTrace.Log("[ZoneSession] Initialized（hook 常駐，模式＝Passive）。");
    }

