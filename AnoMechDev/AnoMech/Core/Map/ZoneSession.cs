    public void Dispose()
    {
        Plugin.AddonLifecycle.UnregisterListener(AddonEvent.PostSetup, "Social", OnSocialPostSetup);

        // To not freeze a player that's disabling/reloading/etc the plugin while not in a Scenario
        //
        // 健檢 2026-09-05 M15：Revert(true) 炸掉時也必須繼續往下拆 hook——detour 沒拆
        // 就卸載插件，下次載入會重打一次（舊 detour 還掛在原生函式上）。
        try
        {
            if (IsActive || IsRestoring)
            {
                Revert(true);
            }
            else
            {
                DisableFirewall(); // 切回 Passive
            }
        }
        catch (Exception ex)
        {
            CrashTrace.Log($"[ZoneSession] Dispose revert failed: {ex}");
        }
        restoration.Dispose();
        disposed = true;
        ++zoneGeneration;
        networkRunGuard = null;

        // hook 現在是常駐的（見建構函式），Dispose 才是真正拆下來的地方。
        sendPacketHook.Disable();
        receivePacketHook.Disable();
        sendPacketHook.Dispose();
        receivePacketHook.Dispose();
    }
