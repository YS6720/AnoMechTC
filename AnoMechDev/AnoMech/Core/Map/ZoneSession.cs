    /// <summary>
    /// 可以起始模擬的私人區域。
    ///
    /// 上游只允許旅館（TerritoryIntendedUse=2），但那是**挑的不變量、不是技術限制**：
    /// 真正需要的性質是「私人、非戰鬥、不會有一堆真人在場」。台服 client 實資料
    /// （tc_TerritoryType.csv）中符合的還有房屋內部與公寓。
    ///
    /// 刻意**不含** IntendedUse=13（住宅區戶外）——那裡有其他玩家。
    ///
    /// ⚠️ 房屋內部的已知代價：回程走 client-side 重載，而家具是伺服器串流的
    /// EventObject ⇒ 回到房屋後家具可能不見，要真的換一次區才會重新拿到。
    /// 旅館幾乎沒有這類物件，這就是上游選旅館的原因。
    /// </summary>
    private static readonly uint[] PrivateStartIntendedUses =
    {
        InnIntendedUse,   //  2 旅館（8 個，上游原本的唯一選項）
        14,               // 14 房屋內部：小屋／公館／宅邸（38 個，個人與部隊共用地圖）
        49,               // 49 公寓房間（1 個）
    };

    public static bool IsInInn()
    {
        var row = Plugin.DataManager.GetExcelSheet<TerritoryType>()
            ?.GetRowOrDefault(Plugin.ClientState.TerritoryType);
        if (row == null) return false;
        return Array.IndexOf(PrivateStartIntendedUses, row.Value.TerritoryIntendedUse.RowId) >= 0;
    }

